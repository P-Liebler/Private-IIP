import { expect, test } from "@playwright/test";

const username = process.env.E2E_USERNAME;
const password = process.env.E2E_PASSWORD;
let portfolio: string | undefined;
const createdInstruments: string[] = [];

test.afterEach(async ({ page }) => {
  if (!username || !password) return;
  const base = process.env.E2E_API_BASE_URL ?? "http://localhost:8000/api/v1";
  const headers = { Origin: process.env.E2E_BASE_URL ?? "http://localhost:3000" };
  await page.request.post(`${base}/auth/login`, { headers, data: { username, password } });
  if (portfolio) await page.request.delete(`${base}/portfolios/${portfolio}`, { headers });
  for (const id of createdInstruments) await page.request.patch(`${base}/instruments/${id}`, { headers, data: { active: false } });
  portfolio = undefined; createdInstruments.length = 0;
});

test("PR5 synthetic private-beta onboarding, reviewed imports, FX, reconciliation and opening position", async ({ page }) => {
  const base = process.env.E2E_API_BASE_URL ?? "http://localhost:8000/api/v1";
  test.skip(!username || !password, "Explicit synthetic login fixture required");
  test.setTimeout(180000);
  const stamp = Date.now().toString(36).toUpperCase();
  const nameA = `SYNTHETIC PR5 A ${stamp}`;
  const nameB = `SYNTHETIC PR5 B ${stamp}`;
  const portfolioName = `SYNTHETIC PR5 Portfolio ${stamp}`;
  const ticker = `P5${stamp}`;
  const figi = `P5${stamp.padStart(10, "0").slice(-10)}`;
  const day = new Date().toISOString().slice(0, 10);
  await page.goto("/login");
  await page.getByLabel("Benutzername").fill(username!);
  await page.getByLabel("Passwort").fill(password!);
  await page.getByRole("button", { name: "Anmelden" }).click();
  await expect(page).toHaveURL(/\/dashboard$/, { timeout: 30000 });
  await page.goto("/instruments");
  async function createInstrument(name: string, currency: string, mic: string, identifier: string) {
    await page.getByLabel("Name", { exact: true }).fill(name);
    await page.getByLabel("Währung", { exact: true }).fill(currency);
    await page.getByLabel("Ticker", { exact: true }).fill(ticker);
    await page.getByLabel("FIGI", { exact: true }).fill(identifier);
    await page.getByLabel("MIC", { exact: true }).fill(mic);
    const response = page.waitForResponse(r => r.url().endsWith("/instruments") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Anlegen", exact: true }).click();
    const result = await response;
    expect(result.status()).toBe(201);
    const instrument = await result.json(); createdInstruments.push(instrument.id);
  }
  await createInstrument(nameA, "USD", "XNYS", figi);
  await createInstrument(nameB, "CHF", "XSWX", `Q5${stamp.padStart(10, "0").slice(-10)}`);
  await page.goto("/portfolios");
  await page.getByLabel("Portfolio-Name").fill(portfolioName);
  await page.getByLabel("Basiswährung").selectOption("CHF");
  await page.getByRole("button", { name: "Erstellen", exact: true }).click();
  await page.getByRole("link", { name: portfolioName, exact: true }).click();
  await expect(page.getByRole("heading", { name: "Portfolio einrichten" })).toBeVisible();
  portfolio = page.url().split("/").pop()!;
  await page.getByRole("button", { name: "Konto einrichten", exact: true }).click();
  await page.getByLabel("Account-Name").fill("SYNTHETIC beta broker");
  await page.getByRole("button", { name: "Account anlegen", exact: true }).click();
  await page.getByLabel("Importkonto").selectOption({ label: "SYNTHETIC beta broker" });
  const csv = `type,trade_date,ticker,quantity,price,amount,currency,fee,tax,external_id\nDEPOSIT,${day},,,,1000,USD,0,0,SYNTHETIC-DEPOSIT-${stamp}\nBUY,${day},${ticker},2,100,,USD,1,1,SYNTHETIC-BUY-${stamp}\n`;
  await page.getByLabel("Transaktionsdatei").setInputFiles({ name: "SYNTHETIC-private-beta.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await page.getByRole("button", { name: "Vorschau prüfen", exact: true }).click();
  await expect(page.getByText(/Identifier AMBIGUOUS/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Import übernehmen", exact: true })).toBeDisabled();
  await page.getByLabel("Instrument für CSV-Zuordnung suchen").fill(nameA);
  await page.getByRole("button", { name: "Zuordnung suchen", exact: true }).click();
  const choice = page.getByLabel("Instrument für CSV-Zeile 3");
  const option = choice.getByRole("option", { name: new RegExp(nameA) });
  await expect(option).toHaveCount(1);
  await choice.selectOption((await option.getAttribute("value"))!);
  await page.getByRole("button", { name: "Vorschau prüfen", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "2 importierbar" })).toBeVisible();
  await page.getByRole("checkbox", { name: /Ich habe Konto, Instrumente/ }).check();
  const commit = page.waitForResponse(r => r.url().endsWith("/transactions/import/commit") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Import übernehmen", exact: true }).click();
  expect((await commit).status()).toBe(200);
  await expect(page.getByRole("status").filter({ hasText: "2 Buchungen übernommen" })).toBeVisible();
  await page.getByRole("button", { name: "Vorschau prüfen", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "2 Duplikate" })).toBeVisible({ timeout: 30000 });
  await page.getByRole("checkbox", { name: /Ich habe Konto, Instrumente/ }).check();
  await page.getByRole("button", { name: "Import übernehmen", exact: true }).click();
  await expect(page.getByRole("status").filter({ hasText: "0 Buchungen übernommen" })).toBeVisible();
  await page.getByRole("link", { name: "Kurs- oder FX-Datei importieren", exact: true }).click();
  async function importMarket(kind: string, data: string) {
    await page.getByLabel("Datentyp").selectOption(kind);
    await page.getByLabel("UTF-8-CSV (max. 5 MB)").setInputFiles({ name: `SYNTHETIC-${kind}.csv`, mimeType: "text/csv", buffer: Buffer.from(data) });
    await page.getByRole("button", { name: "Vorschau erstellen", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Vorschau und Bestätigung" })).toBeVisible({ timeout: 30000 });
    await page.getByRole("checkbox", { name: "Datei, Zuordnung und Ergebnis geprüft", exact: true }).check();
    const response = page.waitForResponse(r => r.url().includes(`/imports/${kind}/commit`) && r.request().method() === "POST");
    await page.getByRole("button", { name: "Explizit übernehmen", exact: true }).click();
    expect((await response).status()).toBe(200);
    await expect(page.getByRole("status").filter({ hasText: "Übernommen:" })).toBeVisible();
  }
  await importMarket("prices", `date,figi,close,currency\n${day},${figi},120,USD\n`);
  await importMarket("fx", `date,base_currency,quote_currency,rate\n${day},USD,CHF,0.9\n`);
  await page.goto(`/portfolios/${portfolio}`);
  await expect(page.getByText("Gesamtwert", { exact: true }).locator("..")).toContainText("934.20 CHF");
  await page.getByRole("button", { name: "Positionen", exact: true }).click();
  await expect(page.getByRole("link", { name: nameA, exact: true })).toBeVisible();
  await page.getByRole("row").filter({ has: page.getByRole("link", { name: nameA, exact: true }) }).getByRole("button", { name: "Details", exact: true }).click();
  await expect(page.getByText(/Tages-Schlusskurs, kein handelbarer Livepreis/)).toBeVisible();
  await page.getByRole("button", { name: "Detailansicht schließen", exact: true }).click();
  await page.getByRole("button", { name: "Depotabgleich", exact: true }).click();
  await page.getByLabel("Auszugskonto").selectOption({ label: "SYNTHETIC beta broker" });
  await page.getByLabel("Belegreferenz").fill("SYNTHETIC private-beta statement");
  await page.getByRole("button", { name: /Vorhandene Instrumente vorbereiten/ }).click();
  await page.getByLabel("Auszugsstückzahl 1").fill("2");
  await page.getByLabel("USD-Cash laut Auszug").fill("798");
  await page.getByLabel("Gesamtwert laut Auszug in CHF (optional)").fill("934.2");
  await page.getByRole("checkbox", { name: /Vollständigen Kontoauszug/ }).check();
  await page.getByRole("button", { name: "Abgleich berechnen", exact: true }).click();
  await expect(page.getByLabel("Abgleichergebnis")).toContainText("MATCHED_ENTERED_FIELDS");
  await page.getByRole("button", { name: "Transaktionen", exact: true }).click();
  await page.getByLabel("Account-Name").fill("SYNTHETIC opening account");
  await page.getByRole("button", { name: "Account anlegen", exact: true }).click();
  await page.locator("#transaction-entry").getByLabel(/^Account/).selectOption({ label: "SYNTHETIC opening account" });
  await page.getByLabel(/^Typ/).selectOption("OPENING_POSITION");
  await page.getByLabel("Instrument suchen", { exact: true }).fill(nameA);
  await page.getByRole("button", { name: "Suchen", exact: true }).click();
  await page.getByRole("button", { name: new RegExp(nameA) }).click();
  await page.getByLabel("Stückzahl", { exact: true }).fill("1");
  await page.getByLabel("Herkunft des Startbestands").fill("SYNTHETIC opening statement, cost unknown");
  const opening = page.waitForResponse(r => r.url().endsWith("/transactions") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Buchen", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Ausdrücklich bestätigen", exact: true }).click();
  const openingResponse = await opening;
  expect(openingResponse.status()).toBe(201);
  const openingRow = await openingResponse.json();
  expect(openingRow.type).toBe("OPENING_POSITION");
  expect(openingRow.amount).toBeNull();
  const valuationAfterOpening = await page.request.get(`${base}/portfolios/${portfolio}/valuation`);
  expect(valuationAfterOpening.ok()).toBe(true);
  expect((await valuationAfterOpening.json()).issues).toEqual(expect.arrayContaining([expect.objectContaining({ code: "UNKNOWN_COST_BASIS" })]));
  await page.getByRole("button", { name: "Datenqualität", exact: true }).click();
  await expect(page.getByText(/Der Einstand ist unbekannt/)).toBeVisible({ timeout: 30000 });
  await page.getByRole("button", { name: "Abmelden", exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
});
